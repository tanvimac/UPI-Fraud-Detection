# src/eda.py
"""Exploratory Data Analysis (EDA) for the synthetic UPI fraud dataset.

This script loads the CSV generated by ``src/data_generator.py`` and
produces several summary statistics and visualisations.
All plots are saved as PNG files in ``reports/eda/``.
The code is deliberately simple and heavily commented so a beginner can
follow each step.
"""

import os
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from datetime import datetime

# ---------------------------------------------------------------------------
# 1️⃣ Load the dataset (use an absolute path – works no matter where the script is run)
# ---------------------------------------------------------------------------
# The CSV lives two levels up from this script: ../data/raw/upi_transactions.csv
csv_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data", "raw", "upi_transactions.csv"))
print(f"Loading data from: {csv_path}")

df = pd.read_csv(csv_path)

# ---------------------------------------------------------------------------
# 2️⃣ Basic sanity checks – missing values & duplicate IDs
# ---------------------------------------------------------------------------
missing_counts = df.isnull().sum()
print("\nMissing values per column:")
print(missing_counts)

dup_ids = df['transaction_id'].duplicated().sum()
print(f"Duplicate transaction_id count: {dup_ids}\n")

# ---------------------------------------------------------------------------
# 3️⃣ Core statistics
# ---------------------------------------------------------------------------
total_tx = len(df)
fraud_tx = df['is_fraud'].sum()
normal_tx = total_tx - fraud_tx
fraud_pct = fraud_tx / total_tx * 100
normal_pct = 100 - fraud_pct

amount_stats = df['amount'].agg(['mean', 'min', 'max'])

print("=== Overview ===")
print(f"Total transactions      : {total_tx}")
print(f"Normal transactions     : {normal_tx} ({normal_pct:.2f}%)")
print(f"Fraudulent transactions: {fraud_tx} ({fraud_pct:.2f}%)")
print("Transaction amount (INR):")
print(f"  Mean : {amount_stats['mean']:.2f}")
print(f"  Min  : {amount_stats['min']:.2f}")
print(f"  Max  : {amount_stats['max']:.2f}\n")

# ---------------------------------------------------------------------------
# 4️⃣ Prepare extra columns for visualisation
# ---------------------------------------------------------------------------
# Extract hour of transaction for time‑of‑day analysis
df['transaction_hour'] = pd.to_datetime(df['transaction_time'], errors='coerce').dt.hour

# ---------------------------------------------------------------------------
# 5️⃣ Plotting helpers
# ---------------------------------------------------------------------------
output_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "reports", "eda"))
os.makedirs(output_dir, exist_ok=True)

def save_plot(fig, name):
    """Save ``fig`` as PNG in the ``reports/eda`` folder.
    ``name`` should be a short filename without extension.
    """
    path = os.path.join(output_dir, f"{name}.png")
    fig.savefig(path, bbox_inches='tight')
    plt.close(fig)
    print(f"Saved chart: {path}")

# ---------------------------------------------------------------------------
# 6️⃣ Normal vs Fraudulent transaction count (bar chart)
# ---------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(6,4))
counts = df['is_fraud'].value_counts().sort_index()
labels = ['Normal', 'Fraud']
ax.bar(labels, counts, color=["#4caf50", "#f44336"])
ax.set_title('Transaction Count: Normal vs Fraud')
ax.set_ylabel('Number of Transactions')
save_plot(fig, "count_normal_vs_fraud")

# ---------------------------------------------------------------------------
# 7️⃣ Transaction amount distribution (histograms for normal & fraud)
# ---------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(8,5))
sns.histplot(data=df, x='amount', hue='is_fraud', bins=50, kde=False,
             palette={0: "#4caf50", 1: "#f44336"}, ax=ax, stat='density')
ax.set_title('Transaction Amount Distribution (Density)')
ax.set_xlabel('Amount (INR)')
ax.set_ylabel('Density')
save_plot(fig, "amount_distribution")

# ---------------------------------------------------------------------------
# 8️⃣ Fraud distribution by merchant_category (bar chart)
# ---------------------------------------------------------------------------
fraud_by_merchant = df[df['is_fraud'] == 1]['merchant_category'].value_counts()
fig, ax = plt.subplots(figsize=(8,4))
sns.barplot(x=fraud_by_merchant.index, y=fraud_by_merchant.values,
            palette='Reds', ax=ax)
ax.set_title('Fraudulent Transactions by Merchant Category')
ax.set_ylabel('Count')
ax.set_xticklabels(ax.get_xticklabels(), rotation=45, ha='right')
save_plot(fig, "fraud_by_merchant")

# ---------------------------------------------------------------------------
# 9️⃣ Fraud distribution by device_type (bar chart)
# ---------------------------------------------------------------------------
fraud_by_device = df[df['is_fraud'] == 1]['device_type'].value_counts()
fig, ax = plt.subplots(figsize=(6,4))
sns.barplot(x=fraud_by_device.index, y=fraud_by_device.values,
            palette='Reds', ax=ax)
ax.set_title('Fraudulent Transactions by Device Type')
ax.set_ylabel('Count')
save_plot(fig, "fraud_by_device")

# ---------------------------------------------------------------------------
# 🔟 Fraud distribution by location (bar chart)
# ---------------------------------------------------------------------------
fraud_by_location = df[df['is_fraud'] == 1]['location'].value_counts()
fig, ax = plt.subplots(figsize=(8,4))
sns.barplot(x=fraud_by_location.index, y=fraud_by_location.values,
            palette='Reds', ax=ax)
ax.set_title('Fraudulent Transactions by Location')
ax.set_ylabel('Count')
ax.set_xticklabels(ax.get_xticklabels(), rotation=45, ha='right')
save_plot(fig, "fraud_by_location")

# ---------------------------------------------------------------------------
# 1️⃣1️⃣ Fraud distribution by transaction hour (bar chart)
# ---------------------------------------------------------------------------
fraud_by_hour = df[df['is_fraud'] == 1]['transaction_hour'].value_counts().sort_index()
fig, ax = plt.subplots(figsize=(10,4))
sns.barplot(x=fraud_by_hour.index, y=fraud_by_hour.values,
            palette='Reds', ax=ax)
ax.set_title('Fraudulent Transactions by Hour of Day')
ax.set_xlabel('Hour (0‑23)')
ax.set_ylabel('Count')
save_plot(fig, "fraud_by_hour")

# ---------------------------------------------------------------------------
# 1️⃣2️⃣ Relationship between transactions_last_1hr and fraud (box plot)
# ---------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(6,4))
sns.boxplot(x='is_fraud', y='transactions_last_1hr', data=df,
            palette=["#4caf50", "#f44336"], ax=ax)
ax.set_title('Recent Transaction Count vs Fraud Label')
ax.set_xlabel('Fraud (0 = Normal, 1 = Fraud)')
ax.set_ylabel('Transactions in Last 1 Hour')
save_plot(fig, "transactions_last_1hr_vs_fraud")

print("\n=== EDA completed successfully ===")
print(f"All charts are stored in: {output_dir}\n")
""" End of script """
